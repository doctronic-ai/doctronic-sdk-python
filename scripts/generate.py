"""Regenerate `src/doctronic/_generated/` from the Doctronic OpenAPI contract.

Usage:
    uv run python scripts/generate.py [--contract <path|url>]

By default it reads `openapi/doctronic-v1.json`, the pinned copy of the public contract at
https://docs.doctronic.ai/openapi/doctronic-v1.json. To take a new contract, replace the pinned
copy, regenerate, and commit both; `regenerate.yml` does this when the docs publish a contract.

The SDK covers the operations an organization API token calls: those whose security names the
`HTTPBearer` scheme. Other operations, such as browser-only ones authenticated another way, are
skipped, along with the schemas only they use.

Writes two files:
- `models.py`: pydantic v2 models for every schema, from datamodel-code-generator. Enums accept
  values the contract doesn't list yet (`doctronic._enums.OpenEnum`).
- `operations.py`: one entry per operation, with the facts the client reads at runtime:
  whether the operation is idempotent (declares an `Idempotency-Key` header), whether it is
  user-scoped (requires `X-Doctronic-User-ID`), whether it streams (`text/event-stream`), whether
  its success envelope requires `data`, the response statuses it documents, and the 409 codes
  that are final: the codes its 409 examples document, minus any the 409 response lists in
  `x-doctronic-retryable-codes`.

CI regenerates from the pinned contract and fails when the output differs from the commit.
"""

from __future__ import annotations

import argparse
import copy
import json
import subprocess
import sys
import tempfile
import urllib.request
from collections.abc import Iterable, Iterator
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
OUTPUT_DIR = ROOT / "src" / "doctronic" / "_generated"
PINNED_CONTRACT = ROOT / "openapi" / "doctronic-v1.json"
HTTP_METHODS = ("get", "put", "post", "patch", "delete")
"""The methods the client sends."""
ALL_METHODS = (*HTTP_METHODS, "head", "options", "trace")
"""Every method a path item can have. The filter checks them all."""
HEADER = "Generated by scripts/generate.py from the Doctronic OpenAPI contract. Do not edit."
ORGANIZATION_SCHEME = "HTTPBearer"
"""The security scheme of the organization API token, the only credential the SDK sends."""
RETRYABLE_CODES = "x-doctronic-retryable-codes"
"""A 409 response's list of error codes that are safe to retry with the same idempotency key."""


def load_contract(source: str) -> dict[str, Any]:
    if source.startswith(("http://", "https://")):
        with urllib.request.urlopen(source, timeout=30) as response:
            raw: bytes = response.read()
    elif Path(source).is_file():
        raw = Path(source).read_bytes()
    else:
        raise SystemExit(
            f"No contract at {source}. Pass --contract with a file path or a URL, or leave it "
            f"out to use the pinned contract at {PINNED_CONTRACT.relative_to(ROOT)}."
        )
    contract: dict[str, Any] = json.loads(raw)
    if not str(contract.get("openapi", "")).startswith("3."):
        raise SystemExit(f"{source} is not an OpenAPI 3 document")
    return contract


def generate_models(contract: dict[str, Any], output: Path) -> None:
    with tempfile.TemporaryDirectory() as tmp:
        contract_path = Path(tmp) / "contract.json"
        contract_path.write_text(json.dumps(contract), encoding="utf-8")
        subprocess.run(
            [
                sys.executable,
                "-m",
                "datamodel_code_generator",
                "--input",
                str(contract_path),
                "--input-file-type",
                "openapi",
                "--output",
                str(output),
                "--output-model-type",
                "pydantic_v2.BaseModel",
                "--target-python-version",
                "3.10",
                "--custom-file-header",
                f"# {HEADER}",
                "--disable-timestamp",
                "--formatters",
                "builtin",
                # Snake-case attributes, with the camelCase wire names as aliases.
                "--snake-case-field",
                "--allow-population-by-field-name",
                "--use-annotated",
                "--field-constraints",
                "--use-union-operator",
                "--use-standard-collections",
                "--use-double-quotes",
                "--use-type-alias",
                "--use-subclass-enum",
                "--use-schema-description",
                "--use-field-description",
                "--output-datetime-class",
                "datetime",
                # Plain strings for emails and URLs: no extra runtime dependencies, and no
                # stricter parsing than the API applies.
                "--type-mappings",
                "string+email=string",
                "string+uri=string",
                # Keep fields the contract doesn't list yet instead of dropping them.
                "--extra-fields",
                "allow",
                # Enums accept values the contract doesn't list yet, so a new value from the API
                # doesn't fail the response.
                "--import-overrides",
                json.dumps({"Enum": "doctronic._enums"}),
            ],
            check=True,
        )


def _documented_codes(response: dict[str, Any]) -> list[str]:
    codes: set[str] = set()
    for media in (response.get("content") or {}).values():
        example = media.get("example")
        if isinstance(example, dict) and isinstance(example.get("code"), str):
            codes.add(example["code"])
        for named in (media.get("examples") or {}).values():
            value = named.get("value")
            if isinstance(value, dict) and isinstance(value.get("code"), str):
                codes.add(value["code"])
    return sorted(codes)


def _resolve_ref(contract: dict[str, Any], ref: str) -> Any:
    if not ref.startswith("#/"):
        raise SystemExit(f"Only local references are supported, not {ref!r}")
    target: Any = contract
    for part in ref.removeprefix("#/").split("/"):
        target = target[part.replace("~1", "/").replace("~0", "~")]
    return target


def _resolve(contract: dict[str, Any], node: dict[str, Any]) -> dict[str, Any]:
    ref = node.get("$ref")
    if not isinstance(ref, str):
        return node
    resolved: dict[str, Any] = _resolve_ref(contract, ref)
    return resolved


def _conflict_codes(contract: dict[str, Any], response: dict[str, Any]) -> list[str]:
    """The 409 codes that are final: documented, and not listed as safe to retry."""
    response = _resolve(contract, response)
    retryable = response.get(RETRYABLE_CODES, [])
    if not isinstance(retryable, list) or not all(
        isinstance(code, str) and code for code in retryable
    ):
        raise SystemExit(f"{RETRYABLE_CODES} must be a list of error codes, not {retryable!r}")
    return sorted(set(_documented_codes(response)) - set(retryable))


def _iter_operations(
    contract: dict[str, Any], methods: tuple[str, ...] = HTTP_METHODS
) -> Iterator[tuple[str, str, dict[str, Any]]]:
    for path, item in contract["paths"].items():
        for method in methods:
            operation = item.get(method)
            if operation is not None:
                yield path, method, operation


def _organization_scoped(contract: dict[str, Any], operation: dict[str, Any]) -> bool:
    security = operation.get("security", contract.get("security", []))
    return any(ORGANIZATION_SCHEME in requirement for requirement in security)


def _check_organization_scheme(contract: dict[str, Any]) -> None:
    scheme = contract.get("components", {}).get("securitySchemes", {}).get(ORGANIZATION_SCHEME)
    if (
        not isinstance(scheme, dict)
        or scheme.get("type") != "http"
        or str(scheme.get("scheme", "")).lower() != "bearer"
    ):
        raise SystemExit(
            f"The contract has no `{ORGANIZATION_SCHEME}` bearer security scheme, so the "
            "generator can't tell which operations take an organization API token."
        )


def _refs(node: Any) -> Iterator[str]:
    if isinstance(node, dict):
        ref = node.get("$ref")
        if isinstance(ref, str):
            yield ref
        for value in node.values():
            yield from _refs(value)
    elif isinstance(node, list):
        for value in node:
            yield from _refs(value)


def _reachable(contract: dict[str, Any], roots: Iterable[Any]) -> set[str]:
    """Every `$ref` the roots reach, directly or through the components they reference."""
    seen: set[str] = set()
    pending = list(roots)
    while pending:
        for ref in _refs(pending.pop()):
            if ref not in seen:
                seen.add(ref)
                pending.append(_resolve_ref(contract, ref))
    return seen


def skipped_operations(contract: dict[str, Any]) -> list[tuple[str, str]]:
    """`(METHOD, path)` for each operation without organization security, which the SDK skips."""
    return [
        (method.upper(), path)
        for path, method, operation in _iter_operations(contract, ALL_METHODS)
        if not _organization_scoped(contract, operation)
    ]


def organization_contract(contract: dict[str, Any]) -> dict[str, Any]:
    """The contract without the operations the SDK skips and the components only they use.

    Components that no operation uses are kept, so the models don't depend on which operations
    happen to reference them.
    """
    _check_organization_scheme(contract)
    pruned = copy.deepcopy(contract)
    skipped: list[dict[str, Any]] = []
    for path in list(pruned["paths"]):
        item = pruned["paths"][path]
        for method in ALL_METHODS:
            operation = item.get(method)
            if operation is not None and not _organization_scoped(contract, operation):
                skipped.append(item.pop(method))
        if not any(method in item for method in ALL_METHODS):
            del pruned["paths"][path]
    if not any(True for _ in _iter_operations(pruned)):
        raise SystemExit(f"No operation in the contract uses the `{ORGANIZATION_SCHEME}` scheme.")
    if not skipped:
        return pruned

    components: dict[str, dict[str, Any]] = pruned.get("components", {})
    skipped_refs = _reachable(pruned, skipped)
    kept_roots: list[Any] = [pruned["paths"]]
    kept_roots += [
        node
        for section, entries in components.items()
        for name, node in entries.items()
        if f"#/components/{section}/{name}" not in skipped_refs
    ]
    for ref in skipped_refs - _reachable(pruned, kept_roots):
        parts = ref.split("/")
        if len(parts) == 4 and parts[:2] == ["#", "components"]:
            components[parts[2]].pop(parts[3], None)
    return pruned


def _data_required(contract: dict[str, Any], responses: dict[str, Any]) -> bool:
    """Whether the JSON success envelope (any 2xx but 202) requires `data`."""
    for status, response in sorted(responses.items()):
        if not status.startswith("2") or status == "202":
            continue
        media = (response.get("content") or {}).get("application/json")
        if media is None:
            continue
        schema = _resolve(contract, media.get("schema") or {})
        return "data" in schema.get("required", [])
    return False


def build_operations(contract: dict[str, Any]) -> list[dict[str, Any]]:
    """The facts the client reads at runtime, for each operation with organization security."""
    contract = organization_contract(contract)
    schemes = contract.get("components", {}).get("securitySchemes", {})
    user_schemes = {
        name
        for name, scheme in schemes.items()
        if scheme.get("type") == "apiKey"
        and scheme.get("in") == "header"
        and scheme.get("name", "").lower() == "x-doctronic-user-id"
    }
    operations: list[dict[str, Any]] = []
    for path, method, operation in _iter_operations(contract):
        shared_parameters = contract["paths"][path].get("parameters", [])
        parameters = [
            _resolve(contract, parameter)
            for parameter in [*shared_parameters, *operation.get("parameters", [])]
        ]
        idempotent = any(
            parameter.get("in") == "header"
            and parameter.get("name", "").lower() == "idempotency-key"
            for parameter in parameters
        )
        security = operation.get("security", contract.get("security", []))
        user_scoped = any(user_schemes & set(requirement) for requirement in security)
        responses: dict[str, Any] = operation.get("responses", {})
        stream = any(
            "text/event-stream" in (response.get("content") or {})
            for status, response in responses.items()
            if status.startswith("2")
        )
        conflict = responses.get("409")
        operations.append(
            {
                "operation_id": operation["operationId"],
                "method": method.upper(),
                "path": path,
                "idempotent": idempotent,
                "user_scoped": user_scoped,
                "stream": stream,
                "data_required": _data_required(contract, responses),
                "statuses": sorted(int(status) for status in responses if status.isdigit()),
                "conflict_codes": _conflict_codes(contract, conflict) if conflict else [],
            }
        )
    return operations


def render_operations(contract: dict[str, Any], operations: list[dict[str, Any]]) -> str:
    lines = [
        f"# {HEADER}",
        "",
        "from __future__ import annotations",
        "",
        "from dataclasses import dataclass",
        "from typing import Final",
        "",
        f"CONTRACT_VERSION: Final = {json.dumps(contract.get('info', {}).get('version', ''))}",
        "",
        "",
        "@dataclass(frozen=True)",
        "class Operation:",
        "    operation_id: str",
        "    method: str",
        "    path: str",
        "    idempotent: bool  # The contract declares an `Idempotency-Key` header.",
        "    user_scoped: bool  # The contract requires `X-Doctronic-User-ID`.",
        "    stream: bool  # The operation responds with `text/event-stream`.",
        "    data_required: bool  # Its JSON success envelope requires `data`.",
        "    statuses: frozenset[int]  # Every response status the contract documents.",
        "    conflict_codes: frozenset[str]  # State-conflict codes documented for 409.",
        "",
        "",
        "OPERATIONS: Final[dict[tuple[str, str], Operation]] = {",
    ]
    for op in operations:
        codes = ", ".join(json.dumps(code) for code in op["conflict_codes"])
        statuses = ", ".join(str(status) for status in op["statuses"])
        lines += [
            f"    ({json.dumps(op['method'])}, {json.dumps(op['path'])}): Operation(",
            f"        operation_id={json.dumps(op['operation_id'])},",
            f"        method={json.dumps(op['method'])},",
            f"        path={json.dumps(op['path'])},",
            f"        idempotent={op['idempotent']},",
            f"        user_scoped={op['user_scoped']},",
            f"        stream={op['stream']},",
            f"        data_required={op['data_required']},",
            f"        statuses=frozenset({{{statuses}}}),",
            f"        conflict_codes=frozenset({{{codes}}}),"
            if codes
            else "        conflict_codes=frozenset(),",
            "    ),",
        ]
    lines += ["}", ""]
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description="Regenerate src/doctronic/_generated/.")
    parser.add_argument(
        "--contract",
        default=str(PINNED_CONTRACT),
        help="Path or URL of the OpenAPI contract (default: the pinned openapi/doctronic-v1.json)",
    )
    args = parser.parse_args()

    contract = load_contract(args.contract)
    operations = build_operations(contract)
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    (OUTPUT_DIR / "__init__.py").write_text(f'"""{HEADER}"""\n', encoding="utf-8")
    models = OUTPUT_DIR / "models.py"
    generate_models(organization_contract(contract), models)
    operations_file = OUTPUT_DIR / "operations.py"
    operations_file.write_text(render_operations(contract, operations), encoding="utf-8")

    files = [str(models), str(operations_file)]
    subprocess.run([sys.executable, "-m", "ruff", "format", "--quiet", *files], check=True)
    shown = (
        PINNED_CONTRACT.relative_to(ROOT)
        if args.contract == str(PINNED_CONTRACT)
        else args.contract
    )
    print(f"Generated models and {len(operations)} operations from {shown}")
    for method, path in skipped_operations(contract):
        print(f"Skipped {method} {path}: its security doesn't use {ORGANIZATION_SCHEME}")


if __name__ == "__main__":
    main()
